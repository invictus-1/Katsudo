"""Cut the Japanese fonts down to the few characters Katsudō shows (活動 and the page-title
kanji), so the app ships a few KB instead of megabytes. Rerun after changing KANJI:

    npm install            (the @fontsource sources are devDependencies)
    python scripts/kanji-fonts.py

Needs fontTools (pip install fonttools). Writes src/fonts/kanji/*.woff2 and kanji.css."""
import glob
import os
from fontTools import subset
from fontTools.ttLib import TTFont

# Every character any kanji text in the app uses. Keep in sync with src/kanji.ts.
KANJI = "活動今日時間軸アプリ入力律通信年取込保存道標設定比較"

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "fonts", "kanji")
FONTS = [
    # family in CSS, @fontsource package, weight
    ("Katsudo Seal", "noto-serif-jp", 900),
    ("Katsudo Dot", "dotgothic16", 400),
    ("Katsudo Heavy", "dela-gothic-one", 400),
    ("Katsudo Code", "m-plus-1-code", 500),
]

os.makedirs(OUT, exist_ok=True)
wanted = {ord(c) for c in KANJI}
css = ["/* Generated by scripts/kanji-fonts.py: Japanese fonts cut to the characters Katsudō shows. */"]
for family, pkg, weight in FONTS:
    missing = set(wanted)
    files = sorted(glob.glob(os.path.join(ROOT, "node_modules", "@fontsource", pkg, "files", f"*-{weight}-normal.woff2")))
    if not files:
        raise SystemExit(f"{pkg}: no files; run npm install")
    part = 0
    for path in files:
        have = set(TTFont(path).getBestCmap()) & missing
        if not have:
            continue
        missing -= have
        name = f"{pkg}-{part}.woff2"
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]
        opts.name_IDs = ["*"]
        font = subset.load_font(path, opts)
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=sorted(have))
        sub.subset(font)
        subset.save_font(font, os.path.join(OUT, name), opts)
        ranges = ",".join(f"U+{c:04X}" for c in sorted(have))
        css.append(f'@font-face {{ font-family: "{family}"; font-weight: {weight}; font-display: block; src: url(./{name}) format("woff2"); unicode-range: {ranges}; }}')
        part += 1
    if missing:
        print(f"{family}: no glyph for {''.join(chr(c) for c in sorted(missing))} (falls back to the next font)")
    size = sum(os.path.getsize(os.path.join(OUT, f"{pkg}-{i}.woff2")) for i in range(part))
    print(f"{family}: {part} file(s), {size / 1024:.1f} KB")
with open(os.path.join(OUT, "kanji.css"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(css) + "\n")
